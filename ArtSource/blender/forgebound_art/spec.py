def asset_filename(category: str, asset_id: str, variant: str | None, state: str, frame: int) -> str:
    parts = ["fb", category, asset_id]
    if variant:
        parts.append(variant)
    parts.append(state)
    if category not in UNFRAMED:
        parts.append(f"{frame:02d}")
    return "_".join(parts) + ".png"


def stable_seed(*parts) -> int:
    """Deterministic seed independent of PYTHONHASHSEED."""
    h = hashlib.sha256("|".join(str(p) for p in parts).encode()).hexdigest()
    return int(h[:8], 16)


# --- Light rig (camera-relative, world space; camera looks along +Y) --------
def _norm(v):
    l = math.sqrt(sum(c * c for c in v))
    return tuple(c / l for c in v)


